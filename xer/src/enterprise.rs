//! Column lists of the enterprise structure tables (OBS, roles and role
//! codes, resource curves, shifts, currencies, funding sources, financial
//! periods and stored period performance), used when OpenXER creates one of
//! them. Tables read from a file keep their own columns. The lists for
//! CURRTYPE, FINTMPL, OBS, SHIFT, SHIFTPER and RSRCCURVDATA are the exact
//! column lists of export files that carry those tables; the others are the
//! database's columns, in its order, without the audit columns (`create_*`,
//! `update_*`, `delete_*`). ROLECATTYPE drops `super_flag` and ends with
//! `export_flag`, as recent export files do for the other code type tables.

/// The enterprise tables in export order: dictionaries before the tables that
/// refer to them.
pub const TABLES: &[&str] = &[
    "CURRTYPE",
    "FINTMPL",
    "FUNDSRC",
    "OBS",
    "ROLECATTYPE",
    "RSRCCURVDATA",
    "SHIFT",
    "FINDATES",
    "ROLECATVAL",
    "ROLES",
    "SHIFTPER",
    "ROLERATE",
    "ROLERCAT",
    "TASKFIN",
    "TRSRCFIN",
];

